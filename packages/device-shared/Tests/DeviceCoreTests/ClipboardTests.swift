import Foundation
import Testing

@testable import DeviceCore

/// A clipboard in memory: what was put on it, how, and what was asked of it.
@MainActor
private final class FakeClipboard: ClipboardAccess {
  var changeCount = 0
  var itemTypes: [[String]] = []
  var held: String?
  var png: Data?
  var sensitive: Bool?
  /// Whether its content was read at all, beyond its types.
  var read = false

  func text() -> String? {
    read = true
    return held
  }

  func picture() -> Data? {
    read = true
    return png
  }

  func write(_ text: String, sensitive: Bool) {
    held = text
    self.sensitive = sensitive
    changeCount += 1
  }

  func clear() {
    held = nil
    changeCount += 1
  }

  /// Another app copied something.
  func copiedElsewhere(_ text: String) {
    held = text
    changeCount += 1
  }
}

/// A clock the test moves by hand.
@MainActor
private final class Later {
  var waiting: [(TimeInterval, @MainActor () -> Void)] = []
  func schedule(_ delay: TimeInterval, _ work: @escaping @MainActor () -> Void) { waiting.append((delay, work)) }
  func pass() {
    let due = waiting
    waiting = []
    for (_, work) in due { work() }
  }
}

@Suite("The clipboard")
@MainActor
struct ClipboardTests {
  @Test func neverReadsPastAConcealedTransientOrAutoGeneratedItem() {
    for marker in [ClipboardMarker.concealed, ClipboardMarker.transient, ClipboardMarker.autoGenerated] {
      let board = FakeClipboard()
      board.held = "hunter2"
      // One plain item and one marked: the marked one stops the whole read.
      board.itemTypes = [["public.utf8-plain-text"], ["public.utf8-plain-text", marker]]
      #expect(ClipboardRead.read(from: board, limit: 100) == .marked, "\(marker)")
      #expect(!board.read, "the content of a marked clipboard is not even read")
    }
  }

  @Test func readsTextCutToTheLimitAndSaysItsWholeLength() {
    let board = FakeClipboard()
    board.itemTypes = [["public.utf8-plain-text"]]
    board.held = "abcdefghij"
    #expect(ClipboardRead.read(from: board, limit: 4) == .text("abcd", length: 10))
  }

  @Test func takesAPictureOnlyWhenAskedAndOnlyWithoutText() {
    let board = FakeClipboard()
    board.itemTypes = [["public.png"]]
    board.png = Data([0x89, 0x50])
    #expect(ClipboardRead.read(from: board, limit: 10) == .nothing)
    #expect(ClipboardRead.read(from: board, limit: 10, pictures: true) == .picture(Data([0x89, 0x50])))
    board.held = "  \n "
    #expect(ClipboardRead.read(from: board, limit: 10, pictures: true) == .picture(Data([0x89, 0x50])), "white space is no text")
    board.png = nil
    #expect(ClipboardRead.read(from: board, limit: 10, pictures: true) == .nothing)
  }

  @Test func marksAndClearsASensitiveCopyAfterAMinute() {
    let board = FakeClipboard()
    let later = Later()
    let writer = ClipboardWriter(board, after: later.schedule)
    writer.copy("482913", sensitive: true)
    #expect(board.sensitive == true)
    #expect(later.waiting.map(\.0) == [ClipboardWriter.sensitiveFor])
    later.pass()
    #expect(board.held == nil)
  }

  @Test func leavesWhatTheOwnerCopiedSince() {
    let board = FakeClipboard()
    let later = Later()
    let writer = ClipboardWriter(board, after: later.schedule)
    writer.copy("482913", sensitive: true)
    board.copiedElsewhere("their own words")
    later.pass()
    #expect(board.held == "their own words")
  }

  @Test func leavesAPlainCopyAloneAndUnmarked() {
    let board = FakeClipboard()
    let later = Later()
    ClipboardWriter(board, after: later.schedule).copy("brew install ripgrep")
    #expect(board.sensitive == false)
    #expect(later.waiting.isEmpty)
    #expect(board.held == "brew install ripgrep")
  }

  @Test func previewsShortAndReadsOnlyWhatTheOwnerSaw() throws {
    let board = FakeClipboard()
    board.itemTypes = [["public.utf8-plain-text"]]
    board.copiedElsewhere(String(repeating: "a", count: 500))
    let preview = try ClipboardResult.answer(ClipboardReadParams(preview: true), from: board)
    #expect(preview.text?.count == ClipboardResult.previewLimit)
    #expect(preview.length == 500)
    let read = try ClipboardResult.answer(ClipboardReadParams(change: preview.change), from: board)
    #expect(read.text?.count == 500)
    // Copied again after the card was drawn: the yes was to something else.
    board.copiedElsewhere("the next thing")
    do {
      _ = try ClipboardResult.answer(ClipboardReadParams(change: preview.change), from: board)
      Issue.record("a clipboard copied over since the preview was read")
    } catch let error as DeviceError {
      #expect(error.code == .changed)
    }
  }

  @Test func refusesAMarkedClipboardEvenForAPreview() {
    let board = FakeClipboard()
    board.held = "hunter2"
    board.itemTypes = [["public.utf8-plain-text", ClipboardMarker.concealed]]
    do {
      _ = try ClipboardResult.answer(ClipboardReadParams(preview: true), from: board)
      Issue.record("a concealed item was read")
    } catch let error as DeviceError {
      #expect(error.code == .concealed)
      #expect(!error.message.contains("hunter2"))
    } catch {
      Issue.record("\(error)")
    }
    #expect(!board.read)
  }

  @Test func answersNoTextForAPictureAlone() throws {
    let board = FakeClipboard()
    board.itemTypes = [["public.png"]]
    board.png = Data([1])
    #expect(try ClipboardResult.answer(ClipboardReadParams(), from: board) == ClipboardResult(change: 0, text: nil, length: 0))
  }

  @Test func marksSensitiveCopiesConcealedAndTransient() {
    #expect(ClipboardMarker.sensitive == ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType"])
    #expect(ClipboardMarker.isMarked([["public.utf8-plain-text"]]) == false)
    #expect(ClipboardMarker.isMarked([]) == false)
  }
}
