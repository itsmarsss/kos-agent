import Foundation

/// The system clipboard as KOS for Mac and KOS for iPhone read and write it, behind a seam so its rules are tested
/// without the system's own (docs/computer.md, The clipboard).
///
/// Reading `changeCount` and `itemTypes` reads no content, so neither asks the owner on a system that guards reads.
@MainActor
public protocol ClipboardAccess: AnyObject {
  /// Goes up each time anything is put on the clipboard, by any app.
  var changeCount: Int { get }
  /// The types each item on the clipboard carries, as uniform type identifiers.
  var itemTypes: [[String]] { get }
  /// The text on it, if any.
  func text() -> String?
  /// The first picture on it as PNG, if any.
  func picture() -> Data?
  /// Puts `text` on it in place of what it held. Sensitive text is marked so clipboard history apps and other
  /// devices leave it alone: concealed and transient on a Mac (`ClipboardMarker.sensitive`), local and expiring
  /// on a phone.
  func write(_ text: String, sensitive: Bool)
  /// Empties it.
  func clear()
}

/// The markers nspasteboard.org defines for what a clipboard holds, which history apps and KOS respect.
public enum ClipboardMarker {
  /// A password manager's copy, or anything else not to be shown or kept.
  public static let concealed = "org.nspasteboard.ConcealedType"
  /// On the clipboard for a moment only: not to be kept in a history.
  public static let transient = "org.nspasteboard.TransientType"
  /// Put there by an app on its own rather than by the owner copying.
  public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"

  /// What KOS marks its own sensitive copies with on a Mac.
  public static let sensitive = [concealed, transient]
  /// Any of these on any item, and KOS reads nothing from the clipboard.
  public static let refused: Set<String> = [concealed, transient, autoGenerated]

  /// Whether any item carries a marker KOS never reads past.
  public static func isMarked(_ itemTypes: [[String]]) -> Bool {
    itemTypes.contains { !refused.isDisjoint(with: $0) }
  }
}

/// What the clipboard held when it was read once, for the owner's Send or for an approved `clipboard.read`.
public enum ClipboardRead: Equatable, Sendable {
  /// Its text, cut to the limit asked for, and how long it was whole.
  case text(String, length: Int)
  /// No text, but a picture, as PNG.
  case picture(Data)
  /// Nothing KOS takes: empty, or neither text nor a picture.
  case nothing
  /// Marked concealed, transient or auto-generated: never read past.
  case marked

  /// Reads `board` once: its markers first, so a marked item is never read at all; then its text, else a picture
  /// when `pictures` is set. Text that is only white space is nothing.
  @MainActor
  public static func read(from board: ClipboardAccess, limit: Int, pictures: Bool = false) -> ClipboardRead {
    if ClipboardMarker.isMarked(board.itemTypes) { return .marked }
    if let text = board.text(), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
      return .text(String(text.prefix(limit)), length: text.count)
    }
    if pictures, let png = board.picture() { return .picture(png) }
    return .nothing
  }
}

/// KOS's own copies onto the clipboard. A sensitive one is marked (`ClipboardAccess.write`) and cleared after a minute,
/// unless something else was put there since: what the owner copied after it is theirs.
@MainActor
public final class ClipboardWriter {
  /// How long a sensitive copy stays.
  public static let sensitiveFor: TimeInterval = 60

  private let board: ClipboardAccess
  private let after: @MainActor (TimeInterval, @escaping @MainActor () -> Void) -> Void

  /// `after` runs its work once the time has passed, on the main actor; tests pass their own clock.
  public init(
    _ board: ClipboardAccess,
    after: @escaping @MainActor (TimeInterval, @escaping @MainActor () -> Void) -> Void = { delay, work in
      DispatchQueue.main.asyncAfter(deadline: .now() + delay) { MainActor.assumeIsolated(work) }
    }
  ) {
    self.board = board
    self.after = after
  }

  public func copy(_ text: String, sensitive: Bool = false) {
    board.write(text, sensitive: sensitive)
    guard sensitive else { return }
    let mine = board.changeCount
    after(Self.sensitiveFor) { [board] in
      if board.changeCount == mine { board.clear() }
    }
  }
}

/// clipboard.read's params: `preview` for the owner's card, `change` (the preview's) for the read they said yes to.
public struct ClipboardReadParams: Decodable, Sendable {
  public let preview: Bool?
  public let change: Int?

  public init(preview: Bool? = nil, change: Int? = nil) {
    self.preview = preview
    self.change = change
  }
}

/// clipboard.read's answer: the clipboard's change count, its text cut to the limit, and its whole length. No text
/// is a clipboard without any (empty, or a picture alone).
public struct ClipboardResult: Encodable, Equatable, Sendable {
  public let change: Int
  public let text: String?
  public let length: Int

  /// As much as a preview carries: enough for the owner to know it, never the whole of a long one.
  public static let previewLimit = 200
  /// As much as one read hands KOS.
  public static let limit = 20_000

  /// The answer to `params`, read once from `board`. A read against a preview is refused once anything was copied
  /// since, so what is read is what the owner saw; a marked item is refused either way.
  @MainActor
  public static func answer(_ params: ClipboardReadParams, from board: ClipboardAccess) throws -> ClipboardResult {
    if let change = params.change, change != board.changeCount {
      throw DeviceError(.changed, "Something else was copied since you were asked, so nothing was read. Ask again to read what is there now.")
    }
    switch ClipboardRead.read(from: board, limit: params.preview == true ? previewLimit : limit) {
    case .marked:
      throw DeviceError(.concealed, "What is on the clipboard is marked private (a password manager's copy, say), so KOS for Mac does not read it.")
    case .text(let text, let length):
      return ClipboardResult(change: board.changeCount, text: text, length: length)
    case .picture, .nothing:
      return ClipboardResult(change: board.changeCount, text: nil, length: 0)
    }
  }
}
